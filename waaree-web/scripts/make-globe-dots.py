"""Generate land dots for the 3D globe.

Inputs (both public): Natural Earth ne_110m_land.geojson (public domain) for world land, and
DataMeet india-composite.geojson (CC-0, official boundary of India as per the Survey of India).
Points are spread evenly with a Fibonacci sphere, kept if on land, and tagged if inside India.
No country borders are drawn on the globe, only land.

Usage: python scripts/make-globe-dots.py ne_110m_land.geojson india-composite.geojson src/features/landing/data/globe-dots.ts
"""
import json
import math
import sys

N = 22000  # points on the whole sphere; ~30% land

land_src, india_src, out = sys.argv[1], sys.argv[2], sys.argv[3]


def rings_of(geojson, decimate=1):
    rings = []
    for f in geojson["features"]:
        g = f["geometry"]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for poly in polys:
            r = poly[0][::decimate] + [poly[0][0]] if len(poly[0]) > decimate * 4 else poly[0]
            xs, ys = [p[0] for p in r], [p[1] for p in r]
            rings.append((r, min(xs), max(xs), min(ys), max(ys)))
    return rings


def inside(rings, lon, lat):
    for r, x0, x1, y0, y1 in rings:
        if not (x0 <= lon <= x1 and y0 <= lat <= y1):
            continue
        c, j = False, len(r) - 1
        for i in range(len(r)):
            xi, yi = r[i]
            xj, yj = r[j]
            if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi + 1e-12) + xi:
                c = not c
            j = i
        if c:
            return True
    return False


land = rings_of(json.load(open(land_src, encoding="utf-8")))
india = rings_of(json.load(open(india_src, encoding="utf-8")), decimate=20)

golden = math.pi * (3 - math.sqrt(5))
dots, india_flags = [], []
for i in range(N):
    y = 1 - (i / (N - 1)) * 2
    lat = math.degrees(math.asin(y))
    lon = math.degrees((golden * i) % (2 * math.pi))
    lon = lon - 360 if lon > 180 else lon
    if lat < -60:  # leave Antarctica out: calmer silhouette
        continue
    in_india = inside(india, lon, lat)
    if in_india or inside(land, lon, lat):
        dots.append((round(lat, 2), round(lon, 2)))
        india_flags.append(1 if in_india else 0)

# India in finer detail: a denser Fibonacci pass, tested only inside India's bounding box.
N_INDIA = 260000
keep = [(d, f) for d, f in zip(dots, india_flags) if not f]
dots, india_flags = [d for d, _ in keep], [0] * len(keep)
for i in range(N_INDIA):
    y = 1 - (i / (N_INDIA - 1)) * 2
    lat = math.degrees(math.asin(y))
    if not (6 <= lat <= 37.5):
        continue
    lon = math.degrees((golden * i) % (2 * math.pi))
    lon = lon - 360 if lon > 180 else lon
    if 68 <= lon <= 97.5 and inside(india, lon, lat):
        dots.append((round(lat, 2), round(lon, 2)))
        india_flags.append(1)

flat = ",".join(f"{a},{b}" for a, b in dots)
mask = "".join(str(x) for x in india_flags)
ts = f"""/**
 * Land dots for the 3D globe: Natural Earth land (public domain) + DataMeet official India
 * boundary (CC-0). Generated by scripts/make-globe-dots.py. Do not hand-edit.
 */

/** {len(dots)} dots as a flat [lat0, lon0, lat1, lon1, ...] array. */
export const GLOBE_DOTS: readonly number[] = [{flat}];

/** One character per dot: "1" = inside India (glows brand green), "0" = elsewhere. */
export const GLOBE_INDIA_MASK = "{mask}";
"""
open(out, "w", encoding="utf-8").write(ts)
print(f"land dots={len(dots)} india={sum(india_flags)} bytes={len(ts)}")
